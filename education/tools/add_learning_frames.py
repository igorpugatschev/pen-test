def block_for(path: Path) -> str:
    return path.parent.name


def frame_for(path: Path) -> str:
    data = BLOCKS[block_for(path)]
    return f"""## Учебная рамка

**Входные требования:** {data["entry"]}

**Результат занятия:** {data["outcome"]}

**Безопасная цель:** {data["target"]}

**Обязательный путь новичка:** {data["beginner"]}

**Углубление:** {data["deepening"]}

**Минимальная проверка успеха:** {data["check"]}

**Эталонный вывод:** {data["output"]}

**Критерии сдачи:** {data["criteria"]}
"""


def replace_frame(text: str, frame: str) -> str:
    if FRAME_HEADER in text:
        start = text.index(FRAME_HEADER)
        criteria = text.find("**Критерии сдачи:**", start)
        if criteria != -1:
            end = text.find("\n\n", criteria)
            if end != -1:
                return text[:start].rstrip() + "\n\n" + frame.rstrip() + text[end:]
            return text[:start].rstrip() + "\n\n" + frame.rstrip() + "\n"

        next_start = text.find(NEXT_SECTION_PREFIX, start + len(FRAME_HEADER))
        if next_start == -1:
            return text[:start].rstrip() + "\n\n" + frame.rstrip() + "\n"
        return text[:start].rstrip() + "\n\n" + frame.rstrip() + "\n" + text[next_start:]

    lines = text.splitlines()
    if not lines or not lines[0].startswith("# "):
        raise ValueError("lesson must start with a level-1 title")
    return lines[0] + "\n\n" + frame.rstrip() + "\n\n" + "\n".join(lines[1:]).lstrip() + "\n"


def main() -> None:
    changed = 0
    for path in sorted(LESSONS.glob("*/*.md")):
        original = path.read_text(encoding="utf-8")
        updated = replace_frame(original, frame_for(path))
        if updated != original:
            path.write_text(updated, encoding="utf-8")
            changed += 1
    print(f"Updated lesson frames: {changed}")


if __name__ == "__main__":
    main()
